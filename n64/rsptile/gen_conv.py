#!/usr/bin/env python3
"""Generate rsp_tile_conv.inc: SNES planar tiles to RDP colour-indexed rows
on the RSP (n64/rsptile, docs/n64/PPU_DESIGN.md step 3).

Lane r of every vector is tile row r. Inputs: $v01 = the tile's row words
for planes 1|0 (high byte plane 1), $v02 planes 3|2, $v03 5|4, $v04 7|6.
A pixel bit is isolated with VAND (vshift element x = 1 << (7 - x), vshift8
element x = 1 << (15 - x)) and moved to its place in an output word by a
multiply: left shifts as VMUDN/VMADN by 2^k (the low product), right shifts
as VMUDL/VMADL by 2^(16-k) (the product >> 16). All terms land at the
accumulator's bit 0 and never overlap, so the accumulator's low slice is
the word (VSAR). Each isolated bit feeds both the normal and the
horizontally flipped word that contain its pixel.

Rows (t8 = DMEM output, row r at t8 + stride * r):
  CI4 (2bpp, 4bpp): 8 bytes: pixels 0-7 (4 bits each, pixel 0 in the high
    nibble), then pixels 7-0.
  CI8 (8bpp): 16 bytes: pixels 0-7, then pixels 7-0.
Clobbers $v05-$v23 and the accumulator; returns with jr ra.
"""
import sys

def pow2(e):
    """Element holding 2^e: vshift e(x) = 2^(7-x), vshift8 e(x) = 2^(15-x)."""
    assert 0 <= e <= 15
    return ("vshift", 7 - e) if e <= 7 else ("vshift8", 15 - e)

def gen(name, bpp):
    out = [f"    .func {name}", f"{name}:"]
    ci8 = bpp == 8
    stride = 16 if ci8 else 8
    # Output words: (normal or flipped word index) -> list of (pixel, plane).
    def place(x, flipped):
        """(word, shift) of pixel x's value in its row."""
        y = 7 - x if flipped else x
        if ci8:
            return (4 if flipped else 0) + (y >> 1), 8 * (1 - (y & 1))
        return (2 if flipped else 0) + (y >> 2), 12 - 4 * (y & 3)
    groups = [[2 * k, 2 * k + 1] for k in range(4)] if ci8 else [[0, 1, 2, 3], [4, 5, 6, 7]]
    for pix in groups:
        temps = {}
        reg = 5
        for x in pix:
            for p in range(bpp):
                src = 1 + p // 2
                mreg = "vshift" if p % 2 == 0 else "vshift8"
                out.append(f"    vand $v{reg:02d}, $v{src:02d}, {mreg}, e({x})")
                temps[(x, p)] = reg
                reg += 1
        assert reg <= 21
        words = sorted({place(x, f)[0] for x in pix for f in (False, True)})
        assert len(words) == 2
        for wi, w in enumerate(words):
            first = True
            for x in pix:
                for f in (False, True):
                    ww, sh = place(x, f)
                    if ww != w:
                        continue
                    for p in range(bpp):
                        srcbit = (7 - x) + 8 * (p % 2)
                        d = sh + p - srcbit
                        t = temps[(x, p)]
                        if d >= 0:
                            assert d <= 14
                            r, e = pow2(d)
                            op = "vmudn" if first else "vmadn"
                        else:
                            r, e = pow2(16 + d)
                            op = "vmudl" if first else "vmadl"
                        out.append(f"    {op} $v23, $v{t:02d}, {r}, e({e})")   # result ignored: the accumulator holds the sum
                        first = False
            dst = 21 + wi
            out.append(f"    vsar $v{dst:02d}, COP2_ACC_LO")
            for r in range(8):
                out.append(f"    ssv $v{dst:02d}, {2 * r}, {stride * r + 2 * w}, t8")
    out += ["    jr ra", "    nop", "    .endfunc", ""]
    return out

lines = ["# Generated by gen_conv.py: do not edit.", ""]
lines += gen("Conv2", 2) + gen("Conv4", 4) + gen("Conv8", 8)
sys.stdout.write("\n".join(lines) + "\n")
