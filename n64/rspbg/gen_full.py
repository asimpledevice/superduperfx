#!/usr/bin/env python3
"""Generate rsp_bg_full.inc: the unrolled full-group decode of rsp_bg.S.

Two variants (4bpp, 2bpp) decode a tile's eight rows into $v08-$v15 (rows
of vertically flipped tiles are loaded in reverse order beforehand). Lines are scheduled in pairs (alternate temporaries) so
consecutive vector instructions do not depend on each other, and the scalar
work for the next tile (its tilemap entry, attributes, address and DMA) is
interleaved one instruction after each vector instruction, so the RSP issues
the two together. Run: gen_full.py > rsp_bg_full.inc
"""

# Next tile (k + 1): entry, attributes (NATTR), DMA into the buffer the
# current tile (t7) does not use, base (NBASE). Uses t0-t5, s0, s4. The DMA
# queue is idle here (Tile_loop waits for it), so the registers are written
# directly. One tile past the end is fetched harmlessly.
PREFETCH = """\
addiu t1, t9, 1
srl t3, s1, 3
addu t3, t3, t1
andi t4, t3, 0x20
srl t4, t4, 2
sll t5, t4, 3
addu t4, t4, t5
andi t3, t3, 0x1f
sll t3, t3, 1
addu t3, t3, t4
andi t5, s5, 7
addu t3, t3, t5
lhu t3, %lo(TMAP)(t3)
lw t2, %lo(PALSH)
srl t4, t3, 10
andi t4, t4, 7
sll t4, t4, 2
sllv t4, t4, t2
addu t4, t4, a1
andi t5, t3, 0x2000
srl t2, t5, 6
addu t4, t4, t2
sll t4, t4, 8
sll t5, t5, 5
or t4, t4, t5
srl t5, t3, 14
sll t5, t5, 16
or t4, t4, t5
sw t4, %lo(NATTR)
lw t2, %lo(CHSH)
andi t3, t3, 0x3ff
sllv t3, t3, t2
addu t3, t3, s2
andi t3, t3, 0x7fff
sll t3, t3, 1
addu s0, s5, t3
srl t5, t7, 3
sll t5, t5, 3
li t2, %lo(TB0)
addiu t2, t2, %lo(TB1)
subu s4, t2, t5
lw t0, %lo(TLEN)
mtc0 s0, COP0_DMA_RAMADDR
mtc0 s4, COP0_DMA_SPADDR
mtc0 t0, COP0_DMA_READ
andi t5, s5, 7
addu s4, s4, t5
sw s4, %lo(NBASE)""".splitlines()

TEMPS = (["$v01", "$v02", "$v03", "$v04"], ["$v16", "$v17", "$v18", "$v19"])
MUL = ["e(6)", "e(5)", "e(4)", "e(3)"]          # 512, 1024, 2048, 4096


def line_ops(bpp, row, out, temps):
    planes = 4 if bpp == 4 else 2
    srcs = [("$v22", "$v26"), ("$v23", "$v26"), ("$v22", "$v27"), ("$v23", "$v27")][:planes]
    mul = [f"vmudn {temps[p]}, {m}, {w}, VE_{row}" for p, (m, w) in enumerate(srcs)]
    msk = [f"vand {temps[p]}, {temps[p]}, vshift8, e(0)" for p in range(planes)]
    mac = [f"{'vmudl' if p == 0 else 'vmadl'} {out}, {temps[p]}, vshift8, {MUL[p]}" for p in range(planes)]
    return mul, msk, mac, f"vor {out}, {out}, $v24, e(0)"


def variant(label, bpp, flip):
    vec, pending = [], []
    for pair in range(4):
        a, b = 2 * pair, 2 * pair + 1
        la = line_ops(bpp, 7 - a if flip else a, f"$v{8 + a:02d}", TEMPS[0])
        lb = line_ops(bpp, 7 - b if flip else b, f"$v{8 + b:02d}", TEMPS[1])
        vec += la[0] + lb[0] + pending + la[1] + lb[1] + la[2] + lb[2] + [la[3]]
        pending = [lb[3]]
    vec += pending
    out = [f"{label}:"]
    scalars = list(PREFETCH)
    for v in vec:
        out.append("    " + v)
        if scalars:
            out.append("    " + scalars.pop(0))
    assert not scalars, f"{label}: {len(scalars)} scalar instructions left over"
    out += ["    b Full_out", "    nop"]
    return out


def main():
    print("# Generated by gen_full.py: do not edit.")
    for label, bpp, flip in (("Dec4", 4, False), ("Dec2", 2, False)):
        print("\n".join(variant(label, bpp, flip)))


main()
