#!/usr/bin/env python3
"""gen_syms.py CORE_ELF OUT [NM] | gen_syms.py --check CORE_ELF EXT_ELF [NM]: the core overlay's symbols (rsp_spc.S) as
`.set C_<name>, <address>` for rsp_spc_ext.S, which runs in the borrowed IMEM
and calls into the core by absolute address. --check: fail if the ext code
is larger than the rspq IMEM it borrows."""
import re, subprocess, sys
if sys.argv[1] == "--check":   # the borrowed-IMEM code must fit what it borrows
    nm = sys.argv[4] if len(sys.argv) > 4 else "mips64-elf-nm"
    def syms(e):
        return {p[2]: int(p[0], 16) for p in (l.split() for l in subprocess.run(
            [nm, e], capture_output=True, text=True, check=True).stdout.splitlines()) if len(p) == 3}
    core, ext = syms(sys.argv[2]), syms(sys.argv[3])
    room = core["_ovl_text_start"] - core["_start"]
    used = ext["_text_end"] - ext["_start"]
    if used > room:
        sys.exit("rsp_spc_ext: %d bytes, but rspq's IMEM is %d" % (used, room))
    print("rsp_spc_ext: %d of %d borrowed IMEM bytes" % (used, room))
    # The core's save areas (EXT_SAVE_OFS 0x300, EXT_DSAVE_OFS 0x600 in
    # rsp_spc.S and spc_rsp.c) and the borrowed DMEM it runs in.
    if room > 0x300:
        sys.exit("rspq's IMEM (%d bytes) outgrew the save area" % room)
    lo = lambda a: a & 0xfff
    if lo(core["_ovl_data_start"]) - lo(core["RSPQ_RESIDENT_END"]) > 0x240:
        sys.exit("rspq's borrowed DMEM outgrew the save area")
    if lo(core["ST"]) < lo(core["RSPQ_RESIDENT_END"]) or lo(core["ST"]) + 0x1b0 > lo(core["_ovl_data_start"]):
        sys.exit("rsp_spc: the state block and scratch do not fit the borrowed DMEM")
    sys.exit(0)
nm = sys.argv[3] if len(sys.argv) > 3 else "mips64-elf-nm"
out = ["# Generated by gen_syms.py from the core overlay (rsp_spc.S)."]
for l in subprocess.run([nm, sys.argv[1]], capture_output=True, text=True, check=True).stdout.splitlines():
    p = l.split()
    if len(p) == 3 and p[1] in "tTdDbBaA" and re.fullmatch(r"[A-Za-z_]\w*", p[2]):
        out.append(".set C_%s, 0x%s" % (p[2], p[0]))
open(sys.argv[2], "w").write("\n".join(out) + "\n")
