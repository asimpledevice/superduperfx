#!/usr/bin/env python3
"""gen_tables.py SPC_C OUT [TRAPS_H]: the RSP SPC700 dispatch table (rsp_spc_tables.inc)
from the C core's own tables (runner/src/snes/spc.c): cycles, addressing mode
and operation per opcode. Entry (16 bits): op index (bits 0-6), mode (7-10),
cycles (12-15). The opcode cases spc.c writes out by hand are mapped here;
every opcode must be mapped exactly once. Opcodes mapped to TRAP (and the
operations in CPU_OPS) end the RSP run before them; the C core runs them."""
import re, sys
src = open(sys.argv[1]).read()
def table(name, n=256):
    m = re.search(r"%s\[%d\] = \{(.*?)\};" % (re.escape(name), n), src, re.S)
    body = re.sub(r"/\*.*?\*/", "", m.group(1))
    v = [int(x, 0) for x in re.findall(r"\d+", body)]
    assert len(v) == n, (name, len(v)); return v
cyc = table("cyclesPerOpcode"); mode = table("k_spc_mode"); op = table("k_spc_op")
mode2 = table("k_spc_mode2"); op2 = table("k_spc_op2")
ops1 = re.search(r"enum \{ SPC_O_NONE, (.*?) \};", src).group(1).split(", ")
ops2 = re.search(r"enum \{ SPC_O2_NONE, (.*?) \};", src).group(1).split(", ")
ops1 = [o.replace("SPC_O_", "") for o in ops1]; ops2 = [o.replace("SPC_O2_", "") for o in ops2]
MODES = ["NONE", "DP", "ABS", "IND", "IDX", "IMM", "DPX", "ABX", "ABY", "IDY", "DPY", "DPDP", "DPIMM", "INDIND"]
SPECIAL = {}  # opcode -> (mode, op)
def sp(ops, m, o):
    for x in ops: SPECIAL[x] = (m, o)
sp([0x00], "NONE", "NOP")
sp([0x01 + 16 * i for i in range(16)], "NONE", "TRAP")          # tcall
sp([0x02 + 32 * i for i in range(8)], "DP", "SET1")
sp([0x12 + 32 * i for i in range(8)], "DP", "CLR1")
sp([0x03 + 32 * i for i in range(8)], "DP", "BBS")
sp([0x13 + 32 * i for i in range(8)], "DP", "BBC")
sp([0x0e, 0x4e, 0x0f, 0x4f, 0x7f, 0xbe, 0xdf, 0xca, 0xea,
    0x0a, 0x2a, 0x4a, 0x6a, 0x8a, 0xaa], "NONE", "TRAP")         # tset1 tclr1 brk pcall reti das daa bit ops
sp([0x1a], "DP", "DECW"); sp([0x3a], "DP", "INCW")
sp([0x5a], "DP", "CMPW"); sp([0x7a], "DP", "ADDW"); sp([0x9a], "DP", "SUBW")
sp([0xba], "DP", "MOVW"); sp([0xda], "DP", "MOVWS")
sp([0x1c], "NONE", "ASLA"); sp([0x3c], "NONE", "ROLA"); sp([0x5c], "NONE", "LSRA"); sp([0x7c], "NONE", "RORA")
sp([0x1f], "NONE", "JMPIAX"); sp([0x2e], "DP", "CBNE"); sp([0xde], "DPX", "CBNE")
sp([0x2f], "NONE", "BRA"); sp([0x3f], "ABS", "CALL"); sp([0x5f], "ABS", "JMP")
sp([0x6e], "DP", "DBNZ"); sp([0x6f], "NONE", "RET")
sp([0x8f], "DPIMM", "MOVMI"); sp([0xfa], "DPDP", "MOVMD")
sp([0x9e], "NONE", "DIV"); sp([0x9f], "NONE", "XCN"); sp([0xcf], "NONE", "MUL")
sp([0xaf], "NONE", "MOVSINDP"); sp([0xbf], "NONE", "MOVINDP"); sp([0xbd], "NONE", "MOVPX")
sp([0xe0], "NONE", "CLRV"); sp([0xed], "NONE", "NOTC"); sp([0xef, 0xff], "NONE", "SLEEP")
sp([0xfe], "NONE", "DBNZY")
sp([0x10 + 32 * i for i in range(8)], "NONE", "BRANCH")
sp([0x20, 0x40, 0x60, 0x80, 0xa0, 0xc0], "NONE", "FLAGS")
sp([0x0d, 0x2d, 0x4d, 0x6d], "NONE", "PUSH"); sp([0x8e, 0xae, 0xce, 0xee], "NONE", "POP")
sp([0x1d, 0x3d, 0x9c, 0xbc, 0xdc, 0xfc], "NONE", "INCDEC")
sp([0x5d, 0x7d, 0x9d, 0xdd, 0xfd], "NONE", "XFER")
# Operations left to the CPU besides the TRAP specials above: rare in sound
# drivers (SMW runs each under 3 times a frame), so their handlers are left
# out of the 4 KB IMEM. Exact either way: the C core runs them.
CPU_OPS = {"ROL", "ROLA", "ROR", "ORMM2", "ANDMM2", "EORMM2", "ADCMM2", "SBCMM2",
           "MOVSINDP", "MOVINDP", "MOVPX", "CLRV", "NOTC", "SLEEP", "MOVMD",
           "CMPW", "DECW", "INCW", "JMPIAX", "DBNZ", "DBNZY",
           "DIV", "CMPY"}   # DIV: 35 a frame in SMW; a vector-unit DIV is the way back
OPS = ops1 + [o + "M2" for o in ops2]
for m, o in sorted(set(SPECIAL.values())):
    if o not in OPS: OPS.append(o)
OPS = [o for o in OPS if o not in CPU_OPS]   # no table slots for them
entries = []
for x in range(256):
    if mode[x]:
        assert x not in SPECIAL, hex(x); m, o = MODES[mode[x]], ops1[op[x] - 1]
    elif mode2[x]:
        assert x not in SPECIAL, hex(x); m, o = MODES[10 + mode2[x]], ops2[op2[x] - 1] + "M2"
    else:
        assert x in SPECIAL, "unmapped opcode %02x" % x; m, o = SPECIAL[x]
    if o in CPU_OPS: m, o = "NONE", "TRAP"
    assert cyc[x] < 16 and len(OPS) <= 128
    entries.append((cyc[x] << 12) | (MODES.index(m) << 7) | OPS.index(o))
with open(sys.argv[2], "w") as f:
    f.write("# Generated by gen_tables.py from runner/src/snes/spc.c.\n    .align 1\nDISPATCH:\n")
    for i in range(0, 256, 8):
        f.write("    .half " + ", ".join("0x%04x" % e for e in entries[i:i + 8]) + "\n")
    f.write("MODETAB:\n" + "".join("    .half M_%s - _start\n" % m for m in MODES))
    f.write("OPTAB:\n" + "".join("    .half OP_%s - _start\n" % o for o in OPS))
if len(sys.argv) > 3:   # the opcodes the RSP leaves to the CPU, for the test
    traps = [x for x in range(256) if (entries[x] & 0x7f) == OPS.index("TRAP")]
    with open(sys.argv[3], "w") as f:
        f.write("/* Generated by gen_tables.py. */\nstatic const uint8_t k_spc_rsp_traps[] = {%s};\n" %
                ", ".join("0x%02x" % x for x in traps))
print("%d ops, %d modes" % (len(OPS), len(MODES)))
