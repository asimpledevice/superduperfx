#!/usr/bin/env python3
"""Choose which generated functions stay native in a size-limited build.

Reads a coverage capture (SNESRECOMP_TIER2_CAPTURE, recorded from an
interpreter-only or mixed build), attributes each interpreted instruction to
the generated function variant that contains it, and keeps the hottest
functions native until a coverage target or a code-size budget is reached.
Every other dispatch entry is written out as a `force_lle <pc24>` line, to be
appended to a copy of the title's bank cfg before regenerating.

Usage:
  select_native_set.py --capture cap.json --gen-dir src/gen \\
      [--coverage 1.0] [--budget-kb 2048 --objects n64-objects-dir] \\
      --out force_lle.cfg

--gen-dir must be the generated tree the capture's program was analysed
from (it supplies program_manifest.json and dispatch_v2.c). --objects is a
directory of the generated code compiled for the target (e.g. with
tools/n64/measure_gen_size.sh); with it, --budget-kb caps native code size.

The selection covers what the capture exercised. Record captures that cover
the gameplay you care about; anything never captured stays interpreted.
"""
import argparse
import collections
import json
import os
import re
import subprocess
import sys

SLOTS = ["M0X0", "M0X1", "M1X0", "M1X1"]


def load_dispatch(path):
    """pc24 -> {variant key: function name} from dispatch_v2.c."""
    entries = {}
    pat = re.compile(r"\s*\{ 0x([0-9A-Fa-f]+)u, \{ ([^}]*) \}")
    with open(path) as f:
        for line in f:
            m = pat.match(line)
            if not m:
                continue
            pc = int(m.group(1), 16)
            names = [x.strip() for x in m.group(2).split(",")]
            entries[pc] = {f"{pc:06X}:{SLOTS[i]}": n for i, n in enumerate(names) if n != "NULL"}
    return entries


def load_sizes(obj_dir, nm):
    sizes = collections.Counter()
    objs = [os.path.join(obj_dir, f) for f in os.listdir(obj_dir) if f.endswith(".o")]
    out = subprocess.run([nm, "-S", "--defined-only"] + objs, capture_output=True,
                         text=True, check=True).stdout
    for line in out.splitlines():
        p = line.split()
        if len(p) == 4 and p[2] in "tT":
            sizes[p[3]] += int(p[1], 16)
    return sizes


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--capture", required=True, action="append",
                    help="coverage capture JSON (repeatable)")
    ap.add_argument("--gen-dir", required=True)
    ap.add_argument("--coverage", type=float, default=1.0,
                    help="stop once this fraction of coverable work is native")
    ap.add_argument("--budget-kb", type=float, default=0.0)
    ap.add_argument("--objects", help="target object files for --budget-kb")
    ap.add_argument("--nm", default=os.path.join(os.environ.get("N64_INST", "/opt/libdragon"),
                                                 "bin", "mips64-elf-nm"))
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    if a.budget_kb and not a.objects:
        sys.exit("--budget-kb needs --objects")

    nodes = json.load(open(os.path.join(a.gen_dir, "program_manifest.json")))["nodes"]
    dispatch = load_dispatch(os.path.join(a.gen_dir, "dispatch_v2.c"))
    fn_of = {k: n for e in dispatch.values() for k, n in e.items()}
    sizes = load_sizes(a.objects, a.nm) if a.objects else collections.Counter()

    by_mx = collections.defaultdict(list)
    for key, v in nodes.items():
        by_mx[key.split(":")[1]].append((v["max_pc24"] - v["min_pc24"], v["min_pc24"], v["max_pc24"], key))
    for lst in by_mx.values():
        lst.sort()  # smallest enclosing node first

    cost = collections.Counter()
    total = 0
    for path in a.capture:
        for r in json.load(open(path)).get("costs", []):
            if r.get("processor") != "snes_cpu":
                continue
            pc = int(r["target_pc24"], 16)
            n = r["interpreted_instructions"]
            total += n
            for _, lo, hi, key in by_mx[r["entry_mx"]]:
                if lo <= pc <= hi:
                    cost[key] += n
                    break
    if not total:
        sys.exit("capture has no interpreted-instruction costs")

    coverable = sum(c for k, c in cost.items() if k in fn_of)
    keep, done, size = set(), 0, 0
    for key, c in cost.most_common():
        if key not in fn_of:
            continue
        if done >= a.coverage * coverable:
            break
        s = sizes.get(fn_of[key], 0)
        if a.budget_kb and size + s > a.budget_kb * 1024:
            continue
        keep.add(int(key.split(":")[0], 16))
        done += c
        size += s

    cold = sorted(set(dispatch) - keep)
    with open(a.out, "w") as f:
        f.write("# Generated by tools/n64/select_native_set.py: functions outside the\n")
        f.write(f"# captured hot set ({len(keep)} entry PCs kept native) stay interpreted.\n")
        for pc in cold:
            f.write(f"force_lle {pc:06x}\n")
    print(f"interpreted work in capture: {total} instructions; "
          f"{100.0 * coverable / total:.1f}% falls in generated functions")
    print(f"kept native: {len(keep)} entry PCs covering {100.0 * done / total:.1f}% of all work"
          + (f", {size / 1024:.0f} KB" if a.objects else ""))
    print(f"forced to the interpreter: {len(cold)} entry PCs -> {a.out}")


if __name__ == "__main__":
    main()
