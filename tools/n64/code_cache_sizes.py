#!/usr/bin/env python3
"""Size table for the N64 code cache: the RAM each routine module takes when
loaded (text + data + bss of its object, aligned, plus the module header),
as C: uint32_t recomp_cache_module_size(const char *name).

Usage: code_cache_sizes.py OUT.c OBJ_DIR [size tool]
"""
import pathlib
import subprocess
import sys

HEADER = 96   # libdragon's loaded-module record and alignment, roughly


def main(out, obj_dir, size_tool="mips64-elf-size"):
    objs = sorted(pathlib.Path(obj_dir).glob("*.o"))
    rows = []
    for i in range(0, len(objs), 500):
        res = subprocess.run([size_tool] + [str(o) for o in objs[i:i + 500]],
                             capture_output=True, text=True, check=True).stdout
        for line in res.splitlines()[1:]:
            p = line.split()
            text, data, bss = int(p[0]), int(p[1]), int(p[2])
            name = pathlib.Path(p[5]).stem
            rows.append((name, (text + data + bss + 15) // 16 * 16 + HEADER))
    rows.sort()
    lines = ["/* Generated by tools/n64/code_cache_sizes.py. */",
             "#include <stdint.h>", "#include <string.h>", "",
             "static const struct { const char *name; uint32_t size; } k_sizes[] = {"]
    lines += [f'  {{ "{n}", {s}u }},' for n, s in rows]
    lines += ["};", "",
              "uint32_t recomp_cache_module_size(const char *name) {",
              "  unsigned lo = 0, hi = sizeof k_sizes / sizeof k_sizes[0];",
              "  while (lo < hi) {",
              "    const unsigned mid = (lo + hi) / 2;",
              "    const int c = strcmp(k_sizes[mid].name, name);",
              "    if (!c) return k_sizes[mid].size;",
              "    if (c < 0) lo = mid + 1; else hi = mid;",
              "  }",
              "  return 0;",
              "}", ""]
    text = "\n".join(lines)
    p = pathlib.Path(out)
    if not p.exists() or p.read_text() != text:
        p.write_text(text)
    print(f"code_cache_sizes: {len(rows)} modules, {sum(s for _, s in rows) / 1e6:.2f} MB")


if __name__ == "__main__":
    main(*sys.argv[1:])
